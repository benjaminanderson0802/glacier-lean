#!/usr/bin/env python3
"""Evaluate small Ollama models through Glacier's local_ai node."""
import argparse
import json
import os
from pathlib import Path
import sys
import threading
import time


ROOT = Path(__file__).resolve().parents[2]
BACKEND = ROOT / "glacier/backend"
sys.path.insert(0, str(BACKEND))
from nodes import local_ai  # noqa: E402


def exact_match(output, expected):
    """Independent checker: trim whitespace and compare case-insensitively."""
    return str(output).strip().casefold() == str(expected).strip().casefold()


def task_passes(output, task):
    """Checker per task. "json": same JSON value (spacing and key order do not matter);
    "list": same comma-separated items in the same order (spaces after commas do not matter);
    otherwise exact_match."""
    kind = task.get("match", "exact")
    if kind == "json":
        try:
            return json.loads(str(output).strip()) == json.loads(task["expected"])
        except ValueError:
            return False
    if kind == "list":
        items = [part.strip().casefold() for part in str(output).strip().split(",")]
        return items == [part.strip().casefold() for part in task["expected"].split(",")]
    return exact_match(output, task["expected"])


def evaluate_task(task, model):
    ctx = {
        "config": {"prompt": task["prompt"], "model": model, "answer_style": "Answer only",
                   "timeout": int(os.environ.get("GLACIER_LOCAL_EVAL_TIMEOUT", "180"))},
        "env_id": "local-model-bench",
        "run_id": task["id"],
    }
    started = time.monotonic()
    result = local_ai.run(ctx)
    elapsed = time.monotonic() - started
    passed = result.get("state") == "done" and task_passes(result.get("output", ""), task)
    return {"id": task["id"], "expected": task["expected"], "output": result.get("output", ""),
            "passed": passed, "elapsed_seconds": elapsed, "usage": result.get("usage", {}),
            "error": result.get("output") if result.get("state") != "done" else ""}


def _peak_rss_sampler(stop, peak):
    try:
        import resource
        python_peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
        while not stop.wait(0.05):
            # Ollama launches a local llama-server for model inference. Sample only
            # those runner processes, not unrelated Ollama or worker processes.
            runner_rss = []
            proc = Path("/proc")
            if proc.is_dir():
                for status in proc.glob("[0-9]*/status"):
                    try:
                        content = status.read_text(errors="ignore")
                        if "Name:\tllama-server" in content:
                            runner_rss.append(int(next(line.split()[1] for line in content.splitlines()
                                                       if line.startswith("VmRSS:"))))
                    except (OSError, StopIteration, ValueError):
                        continue
            peak[0] = max(peak[0], max(runner_rss, default=python_peak))
    except ImportError:
        return


def evaluate_model(model, tasks):
    peak = [0]
    stop = threading.Event()
    sampler = threading.Thread(target=_peak_rss_sampler, args=(stop, peak), daemon=True)
    sampler.start()
    rows = []
    for task in tasks:
        row = evaluate_task(task, model)
        rows.append(row)
        print(f"{model}: {row['id']} {'PASS' if row['passed'] else 'FAIL'}", flush=True)
        # Keep a recoverable record if an Ollama call stalls later in the sequence.
        interim = {"model": model, "passed": sum(item["passed"] for item in rows), "total": len(tasks),
                   "peak_rss_kib": peak[0], "tokens_per_second": 0.0, "seconds": 0.0,
                   "wall_seconds": sum(item["elapsed_seconds"] for item in rows), "rows": rows}
        Path(os.environ.get("GLACIER_LOCAL_EVAL_PROGRESS", Path(__file__).with_name("RESULTS.progress.json"))).write_text(
            json.dumps(interim, indent=2))
    stop.set()
    sampler.join()
    seconds = sum(float(row["usage"].get("generation_seconds", 0)) for row in rows)
    wall_seconds = sum(row["elapsed_seconds"] for row in rows)
    tokens = sum(int(row["usage"].get("tokens_out", 0)) for row in rows)
    return {"model": model, "passed": sum(row["passed"] for row in rows), "total": len(rows),
            "peak_rss_kib": peak[0], "tokens_per_second": tokens / seconds if seconds else 0.0,
            "seconds": seconds, "wall_seconds": wall_seconds, "rows": rows}


def render_results(results):
    lines = ["# Local model evaluation", "", "Generated by `bench/local_models/run_eval.py`.",
             "The score uses an independent check: case-insensitive exact match after trimming outer whitespace, or same JSON value / same list for tasks marked so in tasks.json.",
             "Peak RSS is the maximum sampled RSS of the local Ollama `llama-server` inference runner (or the Python runner on systems where that process cannot be sampled). Tokens/sec is generated tokens divided by Ollama generation time.", "",
             "| Model | Exact matches | Peak runner RSS | Tokens/sec | Generation time | Wall time |", "|---|---:|---:|---:|---:|---:|"]
    for result in results:
        lines.append(f"| `{result['model']}` | {result['passed']}/{result['total']} | {result['peak_rss_kib'] / 1024:.1f} MiB | {result['tokens_per_second']:.2f} | {result['seconds']:.1f} s | {result['wall_seconds']:.1f} s |")
    lines += ["", "## Task results", ""]
    for result in results:
        lines += [f"### {result['model']} ({result['passed']}/{result['total']})", "",
                  "| Task | Expected | Output | Result |", "|---|---|---|---|"]
        for row in result["rows"]:
            output = str(row["output"]).replace("|", "\\|").replace("\n", " ")
            lines.append(f"| {row['id']} | {row['expected']} | {output} | {'PASS' if row['passed'] else 'FAIL'} |")
        lines.append("")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("models", nargs="+", help="Ollama model names to evaluate")
    parser.add_argument("--tasks", type=Path, default=Path(__file__).with_name("tasks.json"))
    parser.add_argument("--results", type=Path, default=Path(__file__).with_name("RESULTS.md"))
    args = parser.parse_args(argv)
    tasks = json.loads(args.tasks.read_text())
    results = [evaluate_model(model, tasks) for model in args.models]
    args.results.write_text(render_results(results) + "\n")
    print(args.results)
    for result in results:
        print(f"{result['model']}: {result['passed']}/{result['total']}, peak RSS {result['peak_rss_kib'] / 1024:.1f} MiB, {result['tokens_per_second']:.2f} tokens/sec")


if __name__ == "__main__":
    main()
